using System;
using System.Collections.Generic;
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Security;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace HyperPdf.Viewer.Generator;

/// <summary>Writes the source made from the icons: the <c>ChromeIcon</c> enum, and the table of outlines and tones the viewer draws from.</summary>
internal static class IconEmitter
{
    /// <summary>The tones an icon may name, in the order of the viewer's <c>IconTone</c> enum.</summary>
    private static readonly string[] Tones = [IconReader.PlainTone, "navigation", "add", "edit", "remove"];

    /// <summary>Writes the source.</summary>
    /// <param name="icons">The icons, in any order.</param>
    /// <returns>The source text.</returns>
    internal static string Emit(IReadOnlyList<IconModel> icons)
    {
        var sorted = new List<IconModel>(icons);
        sorted.Sort(static (left, right) => string.CompareOrdinal(left.Name, right.Name));
        var source = new StringBuilder();
        _ = source.AppendLine("// <auto-generated/>").AppendLine("#nullable enable").AppendLine();
        foreach (var icon in sorted)
        {
            if (ProblemOf(icon) is { Length: > 0 } problem)
            {
                _ = source.Append("#error Icons/Svg/").Append(icon.Name).Append(".svg: ").AppendLine(problem.Replace('\n', ' ').Replace('\r', ' '));
            }
        }

        _ = source.AppendLine("namespace HyperPdf.Viewer.Icons;").AppendLine();
        AppendEnum(source, sorted);
        AppendTable(source, sorted);
        return source.ToString();
    }

    /// <summary>Says what keeps an icon from being generated.</summary>
    /// <param name="icon">The icon.</param>
    /// <returns>The problem, or empty.</returns>
    private static string ProblemOf(IconModel icon)
    {
        if (icon.Error.Length > 0)
        {
            return icon.Error;
        }

        if (!SyntaxFacts.IsValidIdentifier(icon.Name) || icon.Name == "None")
        {
            return "the file's name must be a C# identifier other than None, as it names a member of ChromeIcon";
        }

        return Array.IndexOf(Tones, icon.Tone) < 0 ? $"data-tone=\"{icon.Tone}\" must be one of: {string.Join(", ", Tones)}" : string.Empty;
    }

    /// <summary>Writes the enum with one member for each icon, numbered in the order of their names.</summary>
    /// <param name="source">Receives the source.</param>
    /// <param name="icons">The icons, sorted by name.</param>
    private static void AppendEnum(StringBuilder source, List<IconModel> icons)
    {
        _ = source.AppendLine("/// <summary>The line icons the window's controls show beside or in place of their text. Each is one SVG file in Icons/Svg.</summary>")
            .AppendLine("public enum ChromeIcon")
            .AppendLine("{")
            .AppendLine("    /// <summary>No icon.</summary>")
            .AppendLine("    None = 0,");
        for (var i = 0; i < icons.Count; i++)
        {
            _ = source.AppendLine()
                .Append("    /// <summary>").Append(SecurityElement.Escape(icons[i].Summary)).AppendLine("</summary>")
                .Append("    ").Append(SyntaxFacts.IsValidIdentifier(icons[i].Name) ? icons[i].Name : $"Invalid{Number(i)}").Append(" = ").Append(Number(i + 1)).AppendLine(",");
        }

        _ = source.AppendLine("}").AppendLine();
    }

    /// <summary>Writes the table: the outline of each icon on a line of its own, and the tone of each icon at the icon's number.</summary>
    /// <param name="source">Receives the source.</param>
    /// <param name="icons">The icons, sorted by name.</param>
    private static void AppendTable(StringBuilder source, List<IconModel> icons)
    {
        _ = source.AppendLine("/// <summary>The outlines and tones of the icons, generated from the SVG files in Icons/Svg.</summary>")
            .AppendLine("internal static class IconTable")
            .AppendLine("{")
            .AppendLine("    /// <summary>Gets the outline of every icon, one line each, in the order of <see cref=\"ChromeIcon\"/> from its first icon.</summary>")
            .AppendLine("    internal static global::System.ReadOnlySpan<byte> Paths =>")
            .AppendLine("        \"\"\"");
        foreach (var icon in icons)
        {
            _ = source.Append("        ").AppendLine(icon.Path);
        }

        // The empty line keeps the line end after the last outline inside the literal.
        _ = source.AppendLine()
            .AppendLine("        \"\"\"u8;")
            .AppendLine()
            .AppendLine("    /// <summary>Gets the tone of every icon as a number of IconTone, at the number of the icon.</summary>")
            .Append("    internal static global::System.ReadOnlySpan<byte> Tones => [0");
        foreach (var icon in icons)
        {
            _ = source.Append(", ").Append(Number(Math.Max(0, Array.IndexOf(Tones, icon.Tone))));
        }

        _ = source.AppendLine("];").AppendLine("}");
    }

    /// <summary>Writes a whole number as every culture reads it.</summary>
    /// <param name="value">The number.</param>
    /// <returns>The text.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
}
