using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace HyperPdf.Benchmarks.Generator;

/// <summary>Writes <c>GeneratedCases</c>, which lists every benchmark with each combination of its class's parameters, from the pipeline's models.</summary>
internal static class CaseEmitter
{
    /// <summary>Builds the generated source.</summary>
    /// <param name="benchmarks">The benchmark methods.</param>
    /// <param name="hooks">The set-up and clean-up methods.</param>
    /// <param name="parameters">The parameter attributes.</param>
    /// <returns>The source text.</returns>
    internal static string Emit(IReadOnlyList<BenchmarkModel> benchmarks, IReadOnlyList<HookModel> hooks, IReadOnlyList<ParameterModel> parameters)
    {
        var classes = benchmarks.GroupBy(static b => b.TypeName).OrderBy(static g => g.Key, StringComparer.Ordinal).ToList();
        var text = new StringBuilder();
        _ = text.Append("""
            // <auto-generated/>
            #nullable enable
            namespace AllocationHarness;

            [global::System.CodeDom.Compiler.GeneratedCode("HyperPdf.Benchmarks.Generator", "1.0.0")]
            internal static class GeneratedCases
            {
                internal static void Add(global::System.Collections.Generic.List<CaseEntry> cases)
                {

            """);
        for (var i = 0; i < classes.Count; i++)
        {
            _ = text.AppendLine($"        Add_{i}(cases);");
        }

        _ = text.AppendLine("    }");
        for (var i = 0; i < classes.Count; i++)
        {
            WriteClass(text, classes[i].Key, [.. classes[i].OrderBy(static b => b.Method, StringComparer.Ordinal)], hooks, parameters, i);
        }

        return text.AppendLine("}").ToString();
    }

    /// <summary>Writes the registration and run methods of one class.</summary>
    /// <param name="text">The source so far.</param>
    /// <param name="typeName">The class's global name.</param>
    /// <param name="methods">The class's benchmark methods.</param>
    /// <param name="hooks">Every hook.</param>
    /// <param name="parameters">Every parameter model.</param>
    /// <param name="index">The class's number.</param>
    private static void WriteClass(StringBuilder text, string typeName, List<BenchmarkModel> methods, IReadOnlyList<HookModel> hooks, IReadOnlyList<ParameterModel> parameters, int index)
    {
        var members = parameters.Where(p => p.TypeName == typeName).GroupBy(static p => p.Member).OrderBy(static g => g.Key, StringComparer.Ordinal).Select(static g => g.ToList()).ToList();
        var classHooks = hooks.Where(h => h.TypeName == typeName).ToList();
        _ = text.AppendLine($"    private static void Add_{index}(global::System.Collections.Generic.List<CaseEntry> cases)");
        _ = text.AppendLine("    {");
        for (var m = 0; m < methods.Count; m++)
        {
            WriteRegistration(text, methods[m], members, index, m);
        }

        _ = text.AppendLine("    }");
        for (var m = 0; m < methods.Count; m++)
        {
            WriteRun(text, methods[m], members, classHooks, index, m);
        }
    }

    /// <summary>Writes the loops over a class's parameters that add one case for each combination.</summary>
    /// <param name="text">The source so far.</param>
    /// <param name="method">The benchmark method.</param>
    /// <param name="members">The class's parameter members, each with the models that list its values.</param>
    /// <param name="classIndex">The class's number.</param>
    /// <param name="methodIndex">The method's number.</param>
    private static void WriteRegistration(StringBuilder text, in BenchmarkModel method, List<List<ParameterModel>> members, int classIndex, int methodIndex)
    {
        var filter = Quote(method.FilterName);
        _ = text.AppendLine("        {");
        for (var p = 0; p < members.Count; p++)
        {
            _ = text.AppendLine($"        foreach ({members[p][0].MemberType} p{p} in {Values(members[p])})");
        }

        var parts = string.Concat(members.Select(static (member, p) => $" + Lifecycle.Part({(p == 0 ? string.Empty : "\", \" + ")}{Quote(member[0].Member)}, p{p})"));
        var name = members.Count == 0 ? filter : $"{filter} + \"(\"{parts} + \")\"";
        var arguments = string.Concat(Enumerable.Range(0, members.Count).Select(static p => $", p{p}"));
        _ = text.AppendLine("        {");
        _ = text.AppendLine($"            var name = {name};");
        _ = text.AppendLine($"            cases.Add(new CaseEntry({filter}, name, () => Run_{classIndex}_{methodIndex}(name{arguments})));");
        _ = text.AppendLine("        }");
        _ = text.AppendLine("        }");
    }

    /// <summary>Writes the expression that enumerates every value of a parameter member, joining the lists its attributes give.</summary>
    /// <param name="models">The models of the member.</param>
    /// <returns>The expression.</returns>
    private static string Values(List<ParameterModel> models)
    {
        var expression = $"global::System.Linq.Enumerable.Cast<{models[0].MemberType}>({models[0].Values})";
        for (var i = 1; i < models.Count; i++)
        {
            expression = $"global::System.Linq.Enumerable.Concat({expression}, global::System.Linq.Enumerable.Cast<{models[i].MemberType}>({models[i].Values}))";
        }

        return expression;
    }

    /// <summary>Writes the method that runs one benchmark: a new object, its parameters, and direct calls.</summary>
    /// <param name="text">The source so far.</param>
    /// <param name="method">The benchmark method.</param>
    /// <param name="members">The class's parameter members.</param>
    /// <param name="hooks">The class's hooks.</param>
    /// <param name="classIndex">The class's number.</param>
    /// <param name="methodIndex">The method's number.</param>
    private static void WriteRun(StringBuilder text, in BenchmarkModel method, List<List<ParameterModel>> members, List<HookModel> hooks, int classIndex, int methodIndex)
    {
        var signature = string.Concat(members.Select(static (member, p) => $", {member[0].MemberType} p{p}"));
        _ = text.AppendLine($"    private static async global::System.Threading.Tasks.Task Run_{classIndex}_{methodIndex}(string name{signature})");
        _ = text.AppendLine("    {");
        _ = text.AppendLine($"        var instance = new {method.TypeName}();");
        for (var p = 0; p < members.Count; p++)
        {
            _ = text.AppendLine($"        instance.{members[p][0].Member} = p{p};");
        }

        _ = text.AppendLine($$"""
                    await Lifecycle.RunAsync(
                        name,
                        {{method.OperationsPerInvoke}},
                        {{HookLambda(hooks, HookKind.GlobalSetup, method.Method)}},
                        {{CallLambda(method)}},
                        {{HookLambda(hooks, HookKind.IterationSetup, method.Method)}},
                        {{HookLambda(hooks, HookKind.IterationCleanup, method.Method)}},
                        {{HookLambda(hooks, HookKind.GlobalCleanup, method.Method)}});
                }
            """);
    }

    /// <summary>Writes an expression for a delegate that runs the hooks of a kind that cover a benchmark, or <c>null</c> when there are none.</summary>
    /// <param name="hooks">The class's hooks.</param>
    /// <param name="kind">The hook kind.</param>
    /// <param name="benchmark">The benchmark's method name.</param>
    /// <returns>The expression.</returns>
    private static string HookLambda(List<HookModel> hooks, HookKind kind, string benchmark)
    {
        var covering = hooks.Where(h => h.Kind == kind && (h.Targets.IsEmpty || h.Targets.Items.Contains(benchmark))).OrderBy(static h => h.Method, StringComparer.Ordinal).ToList();
        if (covering.Count == 0)
        {
            return "null";
        }

        var body = new StringBuilder("async () => { ");
        foreach (var hook in covering)
        {
            _ = body.Append(HookStatement(hook));
        }

        return body.Append('}').ToString();
    }

    /// <summary>Writes the statement that calls one hook and waits for it when it returns a task.</summary>
    /// <param name="hook">The hook.</param>
    /// <returns>The statement.</returns>
    private static string HookStatement(in HookModel hook)
    {
        var call = $"instance.{hook.Method}(); ";
        if (!hook.Awaits)
        {
            return call;
        }

        return hook.HasResult ? $"_ = await {call}" : $"await {call}";
    }

    /// <summary>Writes the delegate that makes one measured call of a benchmark.</summary>
    /// <param name="method">The benchmark method.</param>
    /// <returns>The expression, of type <c>Func&lt;ValueTask&gt;</c>.</returns>
    private static string CallLambda(in BenchmarkModel method)
    {
        var call = $"instance.{method.Method}()";
        return method.Return switch
        {
            ReturnKind.Void => $"() => {{ {call}; return default; }}",
            ReturnKind.Task => $"() => new global::System.Threading.Tasks.ValueTask({call})",
            ReturnKind.ValueTask => $"() => {call}",
            ReturnKind.TaskOfResult or ReturnKind.ValueTaskOfResult => $"async () => Lifecycle.Use(await {call})",
            ReturnKind.RefLike => $"() => {{ var result = {call}; return default; }}",
            _ => $"() => {{ Lifecycle.Use({call}); return default; }}",
        };
    }

    /// <summary>Quotes a string as a C# literal.</summary>
    /// <param name="value">The text.</param>
    /// <returns>The literal.</returns>
    private static string Quote(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
