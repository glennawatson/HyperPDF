    /// <summary>Gets the 32x32 DCT, row after row.</summary>
    /// <returns>The matrix.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal static ReadOnlySpan<sbyte> Dct() => DctMatrix;

    /// <summary>Gets the 4x4 DST, row after row: row j is the basis function of frequency j.</summary>
    /// <returns>The matrix.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal static ReadOnlySpan<sbyte> Dst() => DstMatrix;

    /// <summary>Gets the 32x32 DCT with 32 bit entries, row after row.</summary>
    /// <returns>The matrix.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal static ReadOnlySpan<int> DctWide() => DctWideMatrix;

    /// <summary>Gets the 4x4 DST with 32 bit entries, row after row.</summary>
    /// <returns>The matrix.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal static ReadOnlySpan<int> DstWide() => DstWideMatrix;

    /// <summary>Copies a matrix of bytes into a matrix of 32 bit values.</summary>
    /// <param name="matrix">The matrix.</param>
    /// <returns>The widened copy.</returns>
    private static int[] Widen(sbyte[] matrix)
    {
        var wide = new int[matrix.Length];
        for (var i = 0; i < matrix.Length; i++)
        {
            wide[i] = matrix[i];
        }

        return wide;
    }

    /// <summary>Reads the DST from its bytes.</summary>
    /// <returns>The matrix.</returns>
    private static sbyte[] BuildDst()
    {
        var matrix = new sbyte[DstSide * DstSide];
        var bytes = DstBytes;
        for (var i = 0; i < matrix.Length; i++)
        {
            matrix[i] = (sbyte)bytes[i];
        }

        return matrix;
    }

    /// <summary>Builds the whole matrix: the last sixteen positions mirror the first sixteen, with odd frequencies changing sign.</summary>
    /// <returns>The matrix.</returns>
    private static sbyte[] BuildDct()
    {
        var matrix = new sbyte[Side * Side];
        var half = FirstHalf;
        for (var frequency = 0; frequency < Side; frequency++)
        {
            for (var position = 0; position < HalfSide; position++)
            {
                var value = (sbyte)half[(frequency * HalfSide) + position];
                matrix[(frequency * Side) + position] = value;
                matrix[(frequency * Side) + (Side - 1 - position)] = (sbyte)((frequency & 1) == 0 ? value : -value);
            }
        }

        return matrix;
    }
