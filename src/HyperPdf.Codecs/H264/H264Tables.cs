namespace HyperPdf.Codecs.H264;

/// <summary>Small fixed tables of H.264: scan orders, block positions and the chroma quantiser mapping.</summary>
internal static class H264Tables
{
    /// <summary>The first value of the quantiser index from which the chroma quantiser differs from it.</summary>
    internal const int ChromaQpKnee = 30;

    /// <summary>Gets the raster index (row times 8 plus column) of each position in the zig-zag scan of an 8x8 block (Table 8-14).</summary>
    internal static ReadOnlySpan<byte> ZigZag8x8 =>
    [
        0x00, 0x01, 0x08, 0x10, 0x09, 0x02, 0x03, 0x0A, 0x11, 0x18, 0x20, 0x19, 0x12, 0x0B, 0x04, 0x05,
        0x0C, 0x13, 0x1A, 0x21, 0x28, 0x30, 0x29, 0x22, 0x1B, 0x14, 0x0D, 0x06, 0x07, 0x0E, 0x15, 0x1C,
        0x23, 0x2A, 0x31, 0x38, 0x39, 0x32, 0x2B, 0x24, 0x1D, 0x16, 0x0F, 0x17, 0x1E, 0x25, 0x2C, 0x33,
        0x3A, 0x3B, 0x34, 0x2D, 0x26, 0x1F, 0x27, 0x2E, 0x35, 0x3C, 0x3D, 0x36, 0x2F, 0x37, 0x3E, 0x3F,
    ];

    /// <summary>Gets the raster index (row times 4 plus column) of each position in the zig-zag scan of a 4x4 block.</summary>
    internal static ReadOnlySpan<byte> ZigZag4x4 => [0x0, 0x1, 0x4, 0x8, 0x5, 0x2, 0x3, 0x6, 0x9, 0xC, 0xD, 0xA, 0x7, 0xB, 0xE, 0xF];

    /// <summary>Gets the column, in units of 4 pixels, of each luma 4x4 block in the order the bitstream codes them.</summary>
    internal static ReadOnlySpan<byte> BlockColumn => [0x0, 0x1, 0x0, 0x1, 0x2, 0x3, 0x2, 0x3, 0x0, 0x1, 0x0, 0x1, 0x2, 0x3, 0x2, 0x3];

    /// <summary>Gets the row, in units of 4 pixels, of each luma 4x4 block in the order the bitstream codes them.</summary>
    internal static ReadOnlySpan<byte> BlockRow => [0x0, 0x0, 0x1, 0x1, 0x0, 0x0, 0x1, 0x1, 0x2, 0x2, 0x3, 0x3, 0x2, 0x2, 0x3, 0x3];

    /// <summary>Gets the chroma quantiser for each luma-derived index from 30 to 51.</summary>
    private static ReadOnlySpan<byte> ChromaQpAbove => [0x1D, 0x1E, 0x1F, 0x20, 0x20, 0x21, 0x22, 0x22, 0x23, 0x23, 0x24, 0x24, 0x25, 0x25, 0x25, 0x26, 0x26, 0x26, 0x27, 0x27, 0x27, 0x27];

    /// <summary>Maps the quantiser index of a chroma component to its quantiser.</summary>
    /// <param name="index">The index, already clipped to 0 to 51.</param>
    /// <returns>The chroma quantiser.</returns>
    internal static int ChromaQp(int index) => index < ChromaQpKnee ? index : ChromaQpAbove[index - ChromaQpKnee];
}
