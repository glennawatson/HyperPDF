    /// <summary>Resolves a scalar without allocating runtime normalization storage.</summary>
    /// <param name="value">The source scalar.</param>
    /// <returns>The canonical scalar, or the source when normalization would produce multiple scalars.</returns>
    internal static int Resolve(int value)
    {
        var keys = Keys;
        if (value < keys[0] || value > keys[^1])
        {
            return value;
        }

        var index = keys.BinarySearch(value);
        return index < 0 ? value : Values[index];
    }
