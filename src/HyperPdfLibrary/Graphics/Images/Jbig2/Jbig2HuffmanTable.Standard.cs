    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal static Jbig2HuffmanTable GetStandard(int number) => StandardTables[number - 1];

    /// <summary>Builds the standard tables from the line data.</summary>
    /// <returns>The tables.</returns>
    /// <exception cref="InvalidOperationException">The built-in line data is not a valid table.</exception>
    private static Jbig2HuffmanTable[] BuildStandardTables()
    {
        var tables = new Jbig2HuffmanTable[StandardCount];
        var start = 0;
        for (var i = 0; i < StandardCount; i++)
        {
            var count = StandardLineCounts[i];
            var prefixLengths = new int[count];
            for (var j = 0; j < count; j++)
            {
                prefixLengths[j] = StandardPrefixLengths[start + j];
            }

            tables[i] = Create(prefixLengths, StandardRangeLengths.Slice(start, count), StandardRangeLows.Slice(start, count), StandardOutOfBand[i] != 0)
                ?? throw new InvalidOperationException("A standard JBIG2 Huffman table is invalid.");
            start += count;
        }

        return tables;
    }
